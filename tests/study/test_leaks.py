"""The strict deny list (Q12): what may never reach any model input."""

import pytest

from hp import leaks

META = {"cve": "VUL4J-26", "cluster": "apache/struts",
        "commit_hashes": ["3f2310f9088a553daf3556944388ce910fa690cc"],
        "pov_tests": ["org.apache.struts.HandlerTest#testRejectsTraversalPayload"],
        "pov_output": ["expected IllegalArgumentException for crafted payload"]}
PATS = leaks.patterns(META, model_ids=["test-model-2026-01-01"], identity_terms=["Model-A"])


@pytest.mark.parametrize("text, label", [
    ("fixes CVE-2016-3081 in the parser", "cve_id"),
    ("see vul4j-26", "vul4j_id"),
    ("upstream: apache/struts", "github_slug"),
    ("https://github.com/apache/struts/pull/1", "github_slug"),
    ("cherry-picked from 3f2310f9", "commit_hash"),
    ("calls testRejectsTraversalPayload()", "pov_test"),
    ("expected IllegalArgumentException for crafted payload", "pov_output"),
    ("written by test-model-2026-01-01", "model_id"),
    ("// generated by model-a", "identity_term"),
])
def test_forbidden_material_is_caught(text, label):
    assert label in {lab for lab, _ in leaks.find(text, PATS)}
    with pytest.raises(leaks.LeakError):
        leaks.scan(text, PATS)


@pytest.mark.parametrize("text", [
    "package org.apache.struts.dispatcher;",
    "import org.apache.struts.util.ValueStack;",
    "--- a/src/main/java/org/apache/struts/Handler.java",
    "int x = 0x3f2310; // hex literal, not a commit",
    "VUL4J is a benchmark",  # the word alone is not an id
])
def test_packages_imports_and_paths_are_kept(text):
    assert leaks.find(text, PATS) == []


def test_identity_terms_apply_only_to_what_the_generator_wrote():
    """PLAN section 10 item 32: project code that names a vendor (com.google.common,
    a licence header re-added by a full-file rewrite) must not exclude a pair; text
    the generator wrote must."""
    oracle = leaks.oracle_patterns(META)
    ident = leaks.identity_patterns(["test-model-2026-01-01"], ["Google", "Qwen", "Alibaba"])
    base = {"src/H.java": "/* Copyright Alibaba Group */\nimport com.google.common.base.Strings;\n"
                          "class Handler {}\n"}
    context = base["src/H.java"]
    touches_import = ("--- a/src/H.java\n+++ b/src/H.java\n@@ -2 +2 @@\n"
                      "-import com.google.common.base.Strings;\n"
                      "+import com.google.common.base.Strings; \n")
    assert leaks.find_review(context + touches_import, touches_import, oracle, ident, base) == []
    rewrite = ("--- a/src/H.java\n+++ b/src/H.java\n@@ -1,3 +1,3 @@\n"
               "-/* Copyright Alibaba Group */\n+/* Copyright Alibaba Group */\n"
               " import com.google.common.base.Strings;\n-class Handler {}\n+class Handler { }\n")
    assert leaks.find_review(rewrite, rewrite, oracle, ident, base) == []   # re-added header
    for signed in ("+// patch generated by qwen\n", "+// Gemini-style fix by GOOGLE\n",
                   "+// Qwen2.5 suggests this\n"):
        d = "--- a/src/H.java\n+++ b/src/H.java\n@@ -3 +3,2 @@\n class Handler {}\n" + signed
        assert leaks.find_review(d, d, oracle, ident, base), signed
    header = ("--- a/src/H.java\n+++ b/src/H.java\n@@ -3 +3 @@ written by Qwen\n"
              "-class Handler {}\n+class Handler { }\n")
    assert leaks.find_review(header, header, oracle, ident, base) == [("identity_term", "Qwen")]
    oracle_hit = "see CVE-2016-3081\n" + touches_import
    assert ("cve_id", "CVE-2016-3081") in leaks.find_review(oracle_hit, touches_import, oracle,
                                                              ident, base)
    assert leaks.added_text("+++ b/x\n+a\n-b\n c\n+d\n") == "a\nd"

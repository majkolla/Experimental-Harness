"""The strict deny list (Q12): what may never reach any model input."""

import pytest

from hp import leaks

META = {"cve": "VUL4J-26", "cluster": "apache/struts",
        "commit_hashes": ["3f2310f9088a553daf3556944388ce910fa690cc"],
        "pov_tests": ["org.apache.struts.HandlerTest#testRejectsTraversalPayload"],
        "pov_output": ["expected IllegalArgumentException for crafted payload"]}
PATS = leaks.patterns(META, model_ids=["test-model-2026-01-01"], identity_terms=["Model-A"])


@pytest.mark.parametrize("text, label", [
    ("fixes CVE-2016-3081 in the parser", "cve_id"),
    ("see vul4j-26", "vul4j_id"),
    ("upstream: apache/struts", "github_slug"),
    ("https://github.com/apache/struts/pull/1", "github_slug"),
    ("cherry-picked from 3f2310f9", "commit_hash"),
    ("calls testRejectsTraversalPayload()", "pov_test"),
    ("expected IllegalArgumentException for crafted payload", "pov_output"),
    ("written by test-model-2026-01-01", "model_id"),
    ("// generated by model-a", "identity_term"),
])
def test_forbidden_material_is_caught(text, label):
    assert label in {lab for lab, _ in leaks.find(text, PATS)}
    with pytest.raises(leaks.LeakError):
        leaks.scan(text, PATS)


@pytest.mark.parametrize("text", [
    "package org.apache.struts.dispatcher;",
    "import org.apache.struts.util.ValueStack;",
    "--- a/src/main/java/org/apache/struts/Handler.java",
    "int x = 0x3f2310; // hex literal, not a commit",
    "VUL4J is a benchmark",  # the word alone is not an id
])
def test_packages_imports_and_paths_are_kept(text):
    assert leaks.find(text, PATS) == []
